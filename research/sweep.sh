#!/bin/bash
# Compare the open driver against Canon's reference for every model.
# Writes a summary to research/RESULTS.md.
W=${W:-$HOME/.cache/canon-ivec-re}
HERE=$(cd "$(dirname "$0")" && pwd)
export W HERE
doc=$W/t/t3.pdf   # 3 pages: colour, grey, colour

one() {
    id=$1
    ppd=$(grep -l "^\*% model-id: $id\$" "$W"/ppds/*.ppd | head -1)
    W=$W/sweep-$id; mkdir -p "$W"; ln -sfn "$(dirname "$W")/ref" "$W/ref"; ln -sfn "$(dirname "$W")/ppds" "$W/ppds"
    ln -sfn "$(dirname "$W")/ours" "$W/ours"; ln -sfn "$(dirname "$W")/cnijfilter2" "$W/cnijfilter2"
    ln -sfn "$(dirname "$W")/build" "$W/build"; export W
    "$HERE/compare.sh" "$id" "$2"
    "$HERE/compare.sh" "$id" "$2" -o CNGrayscale=True
    bl=$(grep -o '^\*cnivecPaperSize [^:]*\.bl' "$ppd" | head -1 | cut -d' ' -f2)
    photo=$(grep -o '^\*cnivecMediaType [^:]*: "custom-media-type-canon-[0-9]*"' "$ppd" | head -1 | cut -d' ' -f2 | tr -d :)
    [ -n "$bl" ] && "$HERE/compare.sh" "$id" "$2" -o PageSize="$bl" ${photo:+-o MediaType=$photo}
    "$HERE/compare.sh" "$id" "$(dirname "$2")/gray.pdf"
    grep -q 'Duplex DuplexNoTumble' "$ppd" && "$HERE/compare.sh" "$id" "$2" -o Duplex=DuplexNoTumble
    grep -q 'Duplex DuplexTumble' "$ppd" && "$HERE/compare.sh" "$id" "$2" -o Duplex=DuplexTumble
    "$HERE/compare_cmd.sh" "$id" "Clean all"
    "$HERE/compare_cmd.sh" "$id" "PrintSelfTestPage"
    rm -rf "$W"
}
export -f one

grep -h '^\*% model-id:' "$W"/ppds/*.ppd | awk '{print $3}' | grep -v '^generic$' |
    xargs -P"${JOBS:-6}" -I{} bash -c 'one {} '"$doc" > "$W/sweep.txt" 2>&1

{
    echo "# Verification results"
    echo
    echo "Open driver vs Canon cnijfilter2 6.81, 164 models: colour, grayscale, gray-only document, borderless photo, duplex (long and short edge), cleaning and nozzle check, byte comparison after normalising the embedded clock. Maintenance output also ignores two Canon bugs this driver does not copy: the malformed `encoding="job_descriptionutf-8"` declaration and a block of NUL bytes some models get."
    echo "Generated by \`research/sweep.sh\` on $(date -I)."
    echo
    echo "| Result | Count |"
    echo "|---|---|"
    awk '{print $1}' "$W/sweep.txt" | sort | uniq -c | awk '{print "| " $2 " | " $1 " |"}'
    echo
    if grep -qv '^IDENTICAL' "$W/sweep.txt"; then
        echo "## Not identical"
        echo
        grep -v '^IDENTICAL' "$W/sweep.txt" | sort | sed 's/^/    /'
    fi
} > "$HERE/RESULTS.md"
cat "$HERE/RESULTS.md"
